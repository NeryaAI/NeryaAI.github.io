// Usage: node tools/sync-role-avatars.mjs [--check] [--mapping-only]
// Images are supplied by the asset owner. This tool never generates portraits,
// fetches substitutes, changes provenance, or rebuilds the native demo.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { runInNewContext } from 'node:vm';

const root = fileURLToPath(new URL('../', import.meta.url));
const dashboard = path.resolve(process.env.NERYA_DASHBOARD_SOURCE || path.join(root, '../agent/dashboard'));
const ts = createRequire(path.join(dashboard, 'package.json'))('typescript');
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

export async function landingMapping() {
  const source = await readFile(path.join(dashboard, 'lib/roleAvatars.ts'), 'utf8');
  const compiled = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, removeComments: true },
  }).outputText;
  const content = `/* GENERATED by tools/sync-role-avatars.mjs. Source SHA256: ${sha256(source)} */\n(function(root){\nconst exports = {};\n${compiled}\nif(typeof module !== 'undefined' && module.exports) module.exports = exports;\nelse root.NeryaAvatars = exports;\n})(typeof window !== 'undefined' ? window : globalThis);\n`;
  const context = { module: { exports: {} } };
  runInNewContext(content, context);
  return { content, roles: Array.from(context.module.exports.roles) };
}

export function inspectPng(bytes, role) {
  if (bytes.length < 33 || bytes.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a' || bytes.toString('ascii', 12, 16) !== 'IHDR') {
    throw Error(`${role}: expected a PNG portrait`);
  }
  const width = bytes.readUInt32BE(16), height = bytes.readUInt32BE(20);
  if (width !== height || ![256, 512].includes(width)) {
    throw Error(`${role}: expected a generated 256px or 512px square PNG, received ${width}x${height}`);
  }
  return { role, file: `${role}.png`, width, height, bytes: bytes.length, sha256: sha256(bytes) };
}

async function writeOrCheck(destination, bytes, check) {
  if (check) {
    const actual = await readFile(destination).catch(error => {
      if (error.code === 'ENOENT') throw Error(`Missing synchronized file: ${destination}`);
      throw error;
    });
    if (!actual.equals(Buffer.from(bytes))) throw Error(`Role avatar drift: ${destination}`);
    return;
  }
  await mkdir(path.dirname(destination), { recursive: true });
  await writeFile(destination, bytes);
  if (!(await readFile(destination)).equals(Buffer.from(bytes))) throw Error(`Role avatar copy verification failed: ${destination}`);
}

export async function syncRoleAvatars({ check = false, mappingOnly = false } = {}) {
  const mapping = await landingMapping();
  const mappingPath = path.join(root, 'agent-avatars.js');
  if (mappingOnly) {
    await writeOrCheck(mappingPath, mapping.content, check);
    return { roles: mapping.roles, mappingOnly: true };
  }

  // Validate the complete source set before writing anything; missing roles
  // must not quietly become DiceBear, copies of another role, or partial syncs.
  const portraits = [], errors = [];
  for (const role of mapping.roles) {
    try {
      const bytes = await readFile(path.join(root, 'assets/agent-avatars', `${role}.png`));
      portraits.push({ bytes, record: inspectPng(bytes, role) });
    } catch (error) {
      errors.push(error.code === 'ENOENT' ? `${role}: missing generated PNG` : error.message);
    }
  }
  if (errors.length) throw Error(`Generated role avatars are not ready (no files changed):\n${errors.join('\n')}`);
  if (new Set(portraits.map(({ record }) => record.sha256)).size !== mapping.roles.length) {
    throw Error('Every role must have a distinct generated portrait (no files changed).');
  }

  const manifest = {
    version: 1,
    source: 'assets/agent-avatars',
    paths: { website: 'assets/agent-avatars/<role>.png', dashboard: '/branding/agents/<role>.png', demo: './avatars/<role>.png' },
    files: portraits.map(({ record }) => record),
  };
  await writeOrCheck(mappingPath, mapping.content, check);
  for (const directory of [path.join(dashboard, 'public/branding/agents'), path.join(root, 'demo/avatars')]) {
    for (const { bytes, record } of portraits) await writeOrCheck(path.join(directory, record.file), bytes, check);
    await writeOrCheck(path.join(directory, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n', check);
  }
  return manifest;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const flags = process.argv.slice(2);
  try {
    for (const flag of flags) if (!['--check', '--mapping-only'].includes(flag)) throw Error(`Unknown option: ${flag}`);
    const result = await syncRoleAvatars({ check: flags.includes('--check'), mappingOnly: flags.includes('--mapping-only') });
    console.log(`${flags.includes('--check') ? 'PASS' : 'SYNCED'}: ${result.roles?.length || result.files.length} role ${result.mappingOnly ? 'mappings (images not checked)' : 'portraits; website, dashboard and demo bytes match'}`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
